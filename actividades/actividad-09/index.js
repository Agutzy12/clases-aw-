// a. Suma de dos números
console.log("1.a - Suma:", 8 + 4);

// b. Resta de dos números literales
console.log("1.b - Resta:", 15 - 6);

// c. Multiplicación entre dos números literales
console.log("1.c - Multiplicación:", 7 * 3);

// d. División entre dos números literales
console.log("1.d - División:", 20 / 4);

// e. Resto de una división entre dos números literales
console.log("1.e - Resto de la división:", 17 % 5);

// f. Mi nombre
console.log("1.f -", "Agustín Benítez");

// g. Concatenación de dos palabras literales
console.log("1.g -", "Programación" + " " + "web");

// h. Concatenación de tres palabras literales
console.log("1.h -", "Aplicaciones" + " " + "web" + " " + "1");

